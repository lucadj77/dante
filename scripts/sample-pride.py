"""Builds src/lib/samples/en.ts from the Project Gutenberg text of Pride and Prejudice (#1342).

Usage: python3 scripts/sample-pride.py pg1342.txt
"""
import json
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read().replace("\r", "")
parts = re.split(r"\nChapter (\d+)\n", text)
chapters = {int(parts[i]): parts[i + 1] for i in range(1, len(parts), 2)}


def paragraphs(n):
    return [re.sub(r"\s*\n\s*", " ", p).strip() for p in chapters[n].strip().split("\n\n") if p.strip()]


def markdown(p):
    p = re.sub(r"_([^_]+)_", r"*\1*", p)
    p = p.replace("--", "—")
    p = re.sub(r'(^|[\s(—])"', r"\1“", p)
    p = p.replace('"', "”")
    p = re.sub(r"(^|[\s(—“])'", r"\1‘", p)
    return p.replace("'", "’")


def scene(props, paras):
    # Synopses are quoted: they may hold a colon.
    head = "".join(f"{k}: {json.dumps(v, ensure_ascii=False) if k == 'synopsis' else v}\n" for k, v in props.items())
    return f"---\n{head}---\n" + "\n\n".join(markdown(p) for p in paras) + "\n"


M = "Manuscript"
files = {}
# Chapter, scene, paragraphs, properties.
plan = [
    ("010 Netherfield is let", "010 A truth universally acknowledged", (1, 0, None),
     {"synopsis": "Mrs. Bennet hears that a rich young man has taken Netherfield Park.", "status": "revised", "pov": '"[[Mrs. Bennet]]"', "place": '"[[Longbourn]]"', "date": "1811-09-23"}),
    ("020 The visit", "010 Mr. Bennet’s visit", (2, 0, None),
     {"synopsis": "Mr. Bennet has called on Bingley after all, and teases his family with it.", "status": "revised", "pov": '"[[Mr. Bennet]]"', "place": '"[[Longbourn]]"', "date": "1811-10-02"}),
    ("030 The assembly", "010 The invitation", (3, 0, 4),
     {"synopsis": "Bingley returns the visit; Mrs. Bennet plans a dinner he cannot attend.", "status": "draft", "place": '"[[Longbourn]]"', "date": "1811-10-08"}),
    ("030 The assembly", "020 The ball", (3, 4, 14),
     {"synopsis": "At the Meryton assembly Bingley charms everyone and Darcy refuses to dance with Elizabeth.", "status": "revised", "pov": '"[[Elizabeth Bennet|Elizabeth]]"', "place": '"[[Meryton]]"', "date": "1811-10-15"}),
    ("030 The assembly", "030 After the ball", (3, 14, None),
     {"synopsis": "Mrs. Bennet tells her husband everything about the ball.", "status": "draft", "pov": '"[[Mrs. Bennet]]"', "place": '"[[Longbourn]]"', "date": "1811-10-15"}),
    ("040 Two sisters", "010 Jane and Elizabeth", (4, 0, None),
     {"synopsis": "Jane admits she admires Bingley; Elizabeth judges his sisters less kindly.", "status": "draft", "pov": '"[[Elizabeth Bennet|Elizabeth]]"', "place": '"[[Longbourn]]"', "date": "1811-10-16"}),
    ("050 At Lucas Lodge", "010 Talking over the ball", (5, 0, None),
     {"synopsis": "The Lucas and Bennet girls talk over the ball and Darcy’s pride.", "status": "idea", "pov": '"[[Elizabeth Bennet|Elizabeth]]"', "date": "1811-10-17"}),
]
for chapter, name, (n, a, b), props in plan:
    body = scene(props, paragraphs(n)[a:b])
    files[f"{M}/{chapter}/{name}.md"] = body

# A comment and a proposed change by Anna, the co-author of the sample.
ball = f"{M}/030 The assembly/020 The ball.md"
files[ball] = files[ball].replace(
    "“She is tolerable, but not handsome enough to tempt *me*;",
    "{==“She is tolerable, but not handsome enough to tempt *me*;==}{>>@Anna 2026-10-14: The line everyone remembers. Should Elizabeth hear it more clearly?<<}",
).replace("within five minutes", "within {--five--}{>>@Anna 2026-10-14<<}{++a few++}{>>@Anna 2026-10-14<<} minutes", 1)
# A copy Dropbox makes when two people change the same scene at once.
visit = f"{M}/020 The visit/010 Mr. Bennet’s visit.md"
files[f"{M}/020 The visit/010 Mr. Bennet’s visit (Anna's conflicted copy 2026-10-14).md"] = files[visit].replace("earliest", "very first", 1)

out = ["// Generated by scripts/sample-pride.py from Project Gutenberg's Pride and Prejudice (#1342), in the public domain.",
       "export const prideAndPrejudice: Record<string, string> = {"]
for path, content in files.items():
    out.append(f"  {json.dumps(path, ensure_ascii=False)}: {json.dumps(content, ensure_ascii=False)},")
out.append("};\n")
open("src/lib/samples/pride-and-prejudice.ts", "w", encoding="utf-8").write("\n".join(out))
