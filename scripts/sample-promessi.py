"""Builds src/lib/samples/promessi-sposi.ts from the Project Gutenberg text of I promessi sposi (#45334).

Usage: python3 scripts/sample-promessi.py pg45334.txt
"""
import json
import re
import sys

lines = open(sys.argv[1], encoding="utf-8").read().replace("\r", "").split("\n")
text = "\n".join(lines)
start = text.index("                             INTRODUZIONE\n\n")
end = text.index("CAPITOLO III.")
intro, novel = text[start:end].split("I PROMESSI SPOSI", 1)
intro = intro.split("INTRODUZIONE", 1)[1]
chapter1, chapter2 = novel.split("CAPITOLO PRIMO.", 1)[1].split("CAPITOLO II.", 1)


def paragraphs(x):
    x = re.sub(r"\[Illustrazione:[^\]]*\]", "", x, flags=re.S)
    return [re.sub(r"\s*\n\s*", " ", p).strip() for p in x.strip().split("\n\n") if p.strip()]


def markdown(p):
    p = re.sub(r"_([^_]+)_", r"*\1*", p)
    p = re.sub(r"=([^=]+)=", r"**\1**", p)
    p = p.replace("--", "—")
    return p.replace("'", "’")


def scene(props, paras):
    # Synopses are quoted: they may hold a colon.
    head = "".join(f"{k}: {json.dumps(v, ensure_ascii=False) if k == 'synopsis' else v}\n" for k, v in props.items())
    return f"---\n{head}---\n" + "\n\n".join(markdown(p) for p in paras) + "\n"


M = "Manoscritto"
source = {"intro": paragraphs(intro), 1: paragraphs(chapter1), 2: paragraphs(chapter2)}
abbondio, renzo, lucia = '"[[Don Abbondio]]"', '"[[Renzo Tramaglino|Renzo]]"', '"[[Lucia Mondella|Lucia]]"'
paese, canonica = '"[[Il paese]]"', '"[[La casa di don Abbondio]]"'
# Chapter, scene, paragraphs, properties.
plan = [
    ("000 Introduzione", "010 Lo scartafaccio", ("intro", 0, None),
     {"synopsis": "L’autore trova un manoscritto del Seicento e decide di rifarne la dicitura.", "stato": "finita"}),
    ("010 I bravi", "010 La passeggiata", (1, 0, 9),
     {"synopsis": "Il lago di Como, la strada di don Abbondio e le gride contro i bravi.", "stato": "rivista", "pov": abbondio, "luogo": paese, "data": "1628-11-07"}),
    ("010 I bravi", "020 L’incontro", (1, 9, 25),
     {"synopsis": "Due bravi fermano don Abbondio: il matrimonio di Renzo e Lucia non s’ha da fare.", "stato": "rivista", "pov": abbondio, "luogo": paese, "data": "1628-11-07"}),
    ("010 I bravi", "030 Un vaso di terra cotta", (1, 25, 30),
     {"synopsis": "Chi è don Abbondio, e come ha imparato a scansare i contrasti.", "stato": "bozza", "pov": abbondio, "data": "1628-11-07"}),
    ("010 I bravi", "040 Perpetua", (1, 30, None),
     {"synopsis": "Perpetua strappa il segreto a don Abbondio.", "stato": "bozza", "pov": abbondio, "luogo": canonica, "data": "1628-11-07"}),
    ("020 Renzo", "010 La notte", (2, 0, 2),
     {"synopsis": "Don Abbondio passa la notte a cercare una via d’uscita.", "stato": "bozza", "pov": abbondio, "luogo": canonica, "data": "1628-11-08"}),
    ("020 Renzo", "020 Il latinorum", (2, 2, 52),
     {"synopsis": "Renzo viene per le nozze e don Abbondio lo confonde con gli impedimenti.", "stato": "rivista", "pov": renzo, "luogo": canonica, "data": "1628-11-08"}),
    ("020 Renzo", "030 Il nome", (2, 52, 93),
     {"synopsis": "Da Perpetua Renzo intuisce un mistero e costringe il curato a dire il nome di don Rodrigo.", "stato": "idea", "pov": renzo, "luogo": canonica, "data": "1628-11-08"}),
    ("020 Renzo", "040 Lucia", (2, 93, None),
     {"synopsis": "Renzo porta la notizia a Lucia, già vestita da sposa.", "stato": "idea", "pov": renzo, "luogo": '"[[La casa di Lucia]]"', "data": "1628-11-08"}),
]
files = {f"{M}/000 Introduzione/000 Introduzione.md": "---\nkind: prologue\n---\n"}
for chapter, name, (n, a, b), props in plan:
    files[f"{M}/{chapter}/{name}.md"] = scene(props, source[n][a:b])

# A comment and a proposed change by Anna, the co-author of the sample.
meeting = f"{M}/010 I bravi/020 L’incontro.md"
before = files[meeting]
files[meeting] = before.replace(
    "questo matrimonio non s’ha da fare,",
    "{==questo matrimonio non s’ha da fare,==}{>>@Anna 2026-10-14: La frase più famosa del libro: la teniamo in fondo al capitolo?<<}",
    1,
).replace("nè domani,", "{--nè--}{>>@Anna 2026-10-14<<}{++né++}{>>@Anna 2026-10-14<<} domani,", 1)
assert files[meeting].count("@Anna") == 3, "the sample comment did not find its text"
# A copy Dropbox makes when two people change the same scene at once.
latin = f"{M}/020 Renzo/020 Il latinorum.md"
files[f"{M}/020 Renzo/020 Il latinorum (copia in conflitto di Anna 2026-10-14).md"] = files[latin].replace("non si fece molto aspettare", "non si fece aspettare", 1)

out = ["// Generated by scripts/sample-promessi.py from Project Gutenberg's I promessi sposi (#45334), in the public domain.",
       "export const promessiSposi: Record<string, string> = {"]
for path, content in files.items():
    out.append(f"  {json.dumps(path, ensure_ascii=False)}: {json.dumps(content, ensure_ascii=False)},")
out.append("};\n")
open("src/lib/samples/promessi-sposi.ts", "w", encoding="utf-8").write("\n".join(out))
